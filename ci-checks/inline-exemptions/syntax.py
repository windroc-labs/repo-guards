import bisect
import re
from collections.abc import Callable, Iterator

import tree_sitter as ts

Hit = tuple[str, str, str]
Node = ts.Node

GENERATED = re.compile(r"@generated|Code generated .* DO NOT EDIT\.|Generated by the protocol buffer compiler\.\s+DO NOT EDIT!")
JSCPD = re.compile(r"jscpd:ignore-start")


class SourceError(Exception):
    pass


def first_error(node: Node) -> Node:
    for child in node.children:
        if child.has_error or child.is_missing:
            return first_error(child)
    return node


def parse(language: ts.Language, source: bytes) -> Node:
    root = ts.Parser(language).parse(source).root_node
    if root.has_error:
        raise SourceError(f"syntax error at line {first_error(root).start_point.row + 1}")
    return root


def walk(root: Node) -> Iterator[Node]:
    cursor = root.walk()
    while True:
        assert cursor.node
        yield cursor.node
        if cursor.goto_first_child() or cursor.goto_next_sibling():
            continue
        while True:
            if not cursor.goto_parent():
                return
            if cursor.goto_next_sibling():
                break


def text(node: Node | None) -> str:
    return node.text.decode("utf-8") if node and node.text is not None else ""


class Functions:
    """Spans of named functions; a position belongs to the innermost span holding it."""

    def __init__(self, spans: list[tuple[int, int, str]]) -> None:
        self.spans = sorted(spans)
        self.starts = [start for start, _, _ in self.spans]

    def at(self, byte: int) -> str:
        for start, end, name in reversed(self.spans[: bisect.bisect_right(self.starts, byte)]):
            if byte < end:
                return name
        return ""


def own_line(node: Node) -> bool:
    previous = node.prev_sibling
    return previous is None or previous.end_point.row < node.start_point.row


def attached(node: Node, skip: Callable[[Node], bool], declared: Callable[[Node], Node | None]) -> Node | None:
    """The function an own-line comment or attribute sits right above, through other comments and attributes."""
    if not own_line(node):
        return None
    current, following = node, node.next_named_sibling
    while following is not None and skip(following) and following.start_point.row <= current.end_point.row + 1:
        current, following = following, following.next_named_sibling
    if following is None or following.start_point.row > current.end_point.row + 1:
        return None
    return declared(following)


def leading_comments(root: Node, is_comment: Callable[[Node], bool], skip: frozenset[str] = frozenset()) -> list[Node]:
    comments = []
    for child in root.children:
        if is_comment(child):
            comments.append(child)
        elif child.type not in skip:
            break
    return comments


def generated(header: list[Node]) -> list[Hit]:
    return [("generated", "generated", "")] if any(GENERATED.search(text(c)) for c in header) else []


def jscpd(comment: str, function: str) -> list[Hit]:
    return [("jscpd", "ignore", function)] if JSCPD.search(comment) else []
