const usage = "usage: inline-exemptions <root> < NUL-separated paths"

var codeGenerated = regexp.MustCompile(`Code generated .* DO NOT EDIT\.`)

type Occurrence struct {
	Tool     string `json:"tool"`
	File     string `json:"file"`
	Rule     string `json:"rule"`
	Function string `json:"function"`
}

type failure struct {
	File  string `json:"file"`
	Error string `json:"error"`
}

func isGenerated(text string) bool {
	return strings.Contains(text, "@generated") || codeGenerated.MatchString(text) ||
		strings.Contains(text, "Generated by the protocol buffer compiler.  DO NOT EDIT!")
}

// nolintRules returns the linters a golangci-lint //nolint comment names, "*" for all.
func nolintRules(text string) ([]string, bool) {
	rest, ok := strings.CutPrefix(text, "//nolint")
	if !ok {
		return nil, false
	}
	list, named := strings.CutPrefix(rest, ":")
	if !named && rest != "" && !unicode.IsSpace(rune(rest[0])) {
		return nil, false
	}
	var rules []string
	if named {
		if end := strings.IndexFunc(list, unicode.IsSpace); end >= 0 {
			list = list[:end]
		}
		for _, name := range strings.Split(list, ",") {
			if name == "all" {
				name = "*"
			}
			if name != "" {
				rules = append(rules, name)
			}
		}
	}
	if len(rules) == 0 {
		rules = []string{"*"}
	}
	return rules, true
}

func buildExpr(text string) (string, bool) {
	var expr string
	switch {
	case constraint.IsGoBuild(text):
		expr = strings.TrimPrefix(text, "//go:build")
	case constraint.IsPlusBuild(text):
		expr = strings.TrimPrefix(strings.TrimSpace(strings.TrimPrefix(text, "//")), "+build")
	default:
		return "", false
	}
	expr = strings.TrimSpace(expr)
	return expr, expr != ""
}

func funcName(decl *ast.FuncDecl) string {
	if decl.Recv == nil || len(decl.Recv.List) == 0 {
		return decl.Name.Name
	}
	typ := decl.Recv.List[0].Type
	for {
		switch t := typ.(type) {
		case *ast.StarExpr:
			typ = t.X
		case *ast.ParenExpr:
			typ = t.X
		case *ast.IndexExpr:
			typ = t.X
		case *ast.IndexListExpr:
			typ = t.X
		case *ast.Ident:
			return t.Name + "." + decl.Name.Name
		default:
			return decl.Name.Name
		}
	}
}

// commentOnlyLines marks each 1-based line that holds comments and nothing else.
func commentOnlyLines(src []byte, tf *token.File, comments []*ast.CommentGroup) []bool {
	covered := make([]bool, len(src))
	for _, group := range comments {
		for _, c := range group.List {
			for i := tf.Offset(c.Pos()); i < tf.Offset(c.End()); i++ {
				covered[i] = true
			}
		}
	}
	only := make([]bool, tf.LineCount()+2)
	line, comment, code := 1, false, false
	for i := 0; i <= len(src); i++ {
		if i == len(src) || src[i] == '\n' {
			only[line] = comment && !code
			line, comment, code = line+1, false, false
			continue
		}
		switch {
		case covered[i]:
			comment = true
		case src[i] != ' ' && src[i] != '\t' && src[i] != '\r' && src[i] != '\f':
			code = true
		}
	}
	return only
}

type region struct {
	start, end token.Pos
	name       string
}

// funcRegions spans each FuncDecl from the start of the comment-only run directly above it to the end of its last line.
func funcRegions(src []byte, fset *token.FileSet, file *ast.File) []region {
	tf := fset.File(file.Pos())
	only := commentOnlyLines(src, tf, file.Comments)
	var regions []region
	for _, d := range file.Decls {
		decl, ok := d.(*ast.FuncDecl)
		if !ok {
			continue
		}
		top := tf.Line(decl.Pos())
		for top > 1 && only[top-1] {
			top--
		}
		// A comment trailing the closing brace belongs to the function too.
		end := token.Pos(tf.Base() + tf.Size())
		if last := tf.Line(decl.End()); last < tf.LineCount() {
			end = tf.LineStart(last + 1)
		}
		regions = append(regions, region{tf.LineStart(top), end, funcName(decl)})
	}
	return regions
}

func scanGo(name string, src []byte) ([]Occurrence, error) {
	if !utf8.Valid(src) {
		return nil, errors.New("not UTF-8")
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, name, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	var found []Occurrence
	add := func(tool, rule, function string) {
		found = append(found, Occurrence{tool, name, rule, function})
	}
	regions := funcRegions(src, fset, file)
	owner := func(pos token.Pos) string {
		if pos < file.Package {
			return ""
		}
		for _, r := range regions {
			if r.start <= pos && pos < r.end {
				return r.name
			}
		}
		return ""
	}
	generated := false
	for _, group := range file.Comments {
		for _, c := range group.List {
			function := owner(c.Pos())
			if c.Pos() < file.Package && !generated && isGenerated(c.Text) {
				generated = true
				add("generated", "generated", "")
			}
			if strings.Contains(c.Text, "jscpd:ignore-start") {
				add("jscpd", "ignore", function)
			}
			if expr, ok := buildExpr(c.Text); ok {
				add("go-build", expr, "")
			}
			rules, _ := nolintRules(c.Text)
			for _, rule := range rules {
				add("golangci-lint", rule, function)
			}
		}
	}
	for _, d := range file.Decls {
		function := ""
		if decl, ok := d.(*ast.FuncDecl); ok {
			function = funcName(decl)
		}
		ast.Inspect(d, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
				switch sel.Sel.Name {
				case "Skip", "Skipf", "SkipNow":
					add("go-test", sel.Sel.Name, function)
				}
			}
			return true
		})
	}
	return found, nil
}

func scanGoMod(name string, src []byte, nested bool) ([]Occurrence, error) {
	if !utf8.Valid(src) {
		return nil, errors.New("not UTF-8")
	}
	mod, err := modfile.ParseLax(name, src, nil)
	if err != nil {
		return nil, err
	}
	var found []Occurrence
	for _, ignore := range mod.Ignore {
		found = append(found, Occurrence{"go-mod", name, ignore.Path, ""})
	}
	if nested {
		found = append(found, Occurrence{"go-mod", name, "module", ""})
	}
	return found, nil
}

// nestedModules returns the go.mod paths that have another of the given go.mod files in an ancestor directory.
func nestedModules(paths []string) map[string]bool {
	dirs := map[string]bool{}
	for _, p := range paths {
		dirs[path.Dir(p)] = true
	}
	nested := map[string]bool{}
	for _, p := range paths {
		for dir := path.Dir(p); dir != "."; {
			dir = path.Dir(dir)
			if dirs[dir] {
				nested[p] = true
				break
			}
		}
	}
	return nested
}

func isGoMod(p string) bool {
	return path.Base(p) == "go.mod"
}

func scanPath(root, p string, nested bool) ([]Occurrence, error) {
	src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
	if err != nil {
		return nil, err
	}
	if isGoMod(p) {
		return scanGoMod(p, src, nested)
	}
	return scanGo(p, src)
}

func run(args []string, stdin io.Reader, stdout, stderr io.Writer) int {
	if len(args) != 1 {
		fmt.Fprintln(stderr, usage)
		return 2
	}
	root := args[0]
	input, err := io.ReadAll(stdin)
	if err != nil {
		fmt.Fprintf(stderr, "inline-exemptions: reading stdin: %v\n", err)
		return 2
	}
	var paths, mods []string
	for _, p := range strings.Split(string(input), "\x00") {
		if p == "" {
			continue
		}
		paths = append(paths, p)
		if isGoMod(p) {
			mods = append(mods, p)
		}
	}
	nested := nestedModules(mods)
	out := bufio.NewWriter(stdout)
	enc := json.NewEncoder(out)
	enc.SetEscapeHTML(false)
	for _, p := range paths {
		found, err := scanPath(root, p, nested[p])
		var records []any
		if err != nil {
			records = append(records, failure{p, err.Error()})
		}
		for _, o := range found {
			records = append(records, o)
		}
		for _, r := range records {
			if err := enc.Encode(r); err != nil {
				fmt.Fprintf(stderr, "inline-exemptions: writing stdout: %v\n", err)
				return 2
			}
		}
	}
	if err := out.Flush(); err != nil {
		fmt.Fprintf(stderr, "inline-exemptions: writing stdout: %v\n", err)
		return 2
	}
	return 0
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdin, os.Stdout, os.Stderr))
}
