import { readFileSync, realpathSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

export interface Occurrence {
  tool: string;
  file: string;
  rule: string;
  function: string;
}

export interface FileError {
  file: string;
  error: string;
}

export type Output = Occurrence | FileError;

interface Comment {
  pos: number;
  end: number;
  multiLine: boolean;
  ownLine: boolean;
}

interface Context {
  name: string;
  start: number;
  end: number;
  attach: number;
}

interface Found {
  pos: number;
  tool: string;
  rule: string;
  function: string;
}

const KINDS: Record<string, ts.ScriptKind> = {
  ".ts": ts.ScriptKind.TS,
  ".mts": ts.ScriptKind.TS,
  ".cts": ts.ScriptKind.TS,
  ".tsx": ts.ScriptKind.TSX,
  ".js": ts.ScriptKind.JS,
  ".mjs": ts.ScriptKind.JS,
  ".cjs": ts.ScriptKind.JS,
  ".jsx": ts.ScriptKind.JSX,
};

const TEST_ROOTS = new Set(["test", "it", "describe", "suite"]);
const X_ROOTS = new Set(["xit", "xtest", "xdescribe"]);
const MARKERS = new Set(["skip", "todo", "fails", "skipIf", "runIf"]);
const CONTEXT_NAMES = new Set(["ctx", "context"]);

const TSC = /^[\s*/]*@(ts-expect-error|ts-ignore)/;
const TSC_NOCHECK = /^[\s*/]*@ts-nocheck(?![^\s:])/i;
const ESLINT_DISABLE = /^(eslint-disable(?:-next-line|-line)?)(?:\s+([\s\S]*))?$/;
const ESLINT_CONFIG = /^eslint\s+([\s\S]*)$/;
const ESLINT_DESCRIPTION = /\s-{2,}\s[\s\S]*$/;
const COVERAGE = /^(?:v8|c8|istanbul)\s+ignore\s+(next|start|if|else|file)(?![\w-])/;
const PUBLIC = /(?:^|\s)@public(?![\w$-])/m;
const GENERATED = [
  /@generated/,
  /Code generated .* DO NOT EDIT\./,
  /Generated by the protocol buffer compiler\. {2}DO NOT EDIT!/,
];

function unwrap(node: ts.Node): ts.Node {
  let n = node;
  while (ts.isParenthesizedExpression(n) || ts.isAsExpression(n) || ts.isSatisfiesExpression(n)) {
    n = n.expression;
  }
  return n;
}

function isFunction(node: ts.Node | undefined): node is ts.ArrowFunction | ts.FunctionExpression {
  if (node === undefined) return false;
  const n = unwrap(node);
  return ts.isArrowFunction(n) || ts.isFunctionExpression(n);
}

function initializerOwner(node: ts.Node): ts.Node {
  let n = node.parent;
  while (ts.isParenthesizedExpression(n) || ts.isAsExpression(n) || ts.isSatisfiesExpression(n)) {
    n = n.parent;
  }
  return n;
}

function variableName(expression: ts.Node): string | undefined {
  const owner = initializerOwner(expression);
  if (ts.isVariableDeclaration(owner) && ts.isIdentifier(owner.name)) return owner.name.text;
  return undefined;
}

function hasDefault(node: ts.Node): boolean {
  return (
    ts.canHaveModifiers(node) &&
    (ts.getModifiers(node) ?? []).some((m) => m.kind === ts.SyntaxKind.DefaultKeyword)
  );
}

function className(node: ts.ClassLikeDeclaration): string {
  if (ts.isClassExpression(node)) {
    const name = variableName(node);
    if (name !== undefined) return name;
  }
  if (node.name !== undefined) return node.name.text;
  return hasDefault(node) ? "default" : "";
}

function memberName(name: ts.PropertyName, file: ts.SourceFile): string {
  if (ts.isIdentifier(name) || ts.isPrivateIdentifier(name) || ts.isStringLiteral(name)) {
    return name.text;
  }
  if (ts.isNumericLiteral(name)) return name.text;
  return name.getText(file);
}

function qualified(owner: string, member: string): string {
  return owner === "" ? member : `${owner}.${member}`;
}

function contexts(file: ts.SourceFile): Context[] {
  const found: Context[] = [];
  const named = new Set<ts.Node>();
  const add = (name: string, range: ts.Node, attach: ts.Node = range): void => {
    found.push({ name, start: range.getStart(file), end: range.end, attach: attach.getStart(file) });
  };
  const ownerName = (member: ts.Node): string | undefined => {
    const parent = member.parent;
    if (ts.isClassLike(parent)) return className(parent);
    if (ts.isObjectLiteralExpression(parent)) return variableName(parent);
    return undefined;
  };
  const visit = (node: ts.Node): void => {
    if (ts.isFunctionDeclaration(node)) {
      const name = node.name?.text ?? (hasDefault(node) ? "default" : undefined);
      if (name !== undefined) add(name, node);
    } else if (
      ts.isMethodDeclaration(node) ||
      ts.isGetAccessorDeclaration(node) ||
      ts.isSetAccessorDeclaration(node) ||
      ts.isConstructorDeclaration(node)
    ) {
      const owner = ownerName(node);
      const member = ts.isConstructorDeclaration(node)
        ? "constructor"
        : memberName(node.name, file);
      if (owner !== undefined) add(qualified(owner, member), node);
    } else if (
      (ts.isPropertyDeclaration(node) || ts.isPropertyAssignment(node)) &&
      isFunction(node.initializer)
    ) {
      const owner = ownerName(node);
      if (owner !== undefined) {
        add(qualified(owner, memberName(node.name, file)), node);
        named.add(unwrap(node.initializer));
      }
    } else if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
      if (isFunction(node.initializer)) {
        const list = node.parent;
        const statement =
          ts.isVariableDeclarationList(list) &&
          list.declarations[0] === node &&
          ts.isVariableStatement(list.parent)
            ? list.parent
            : node;
        add(node.name.text, node, statement);
        named.add(unwrap(node.initializer));
      }
    } else if (ts.isExportAssignment(node) && !node.isExportEquals && isFunction(node.expression)) {
      const fn = unwrap(node.expression);
      const name = ts.isFunctionExpression(fn) ? fn.name?.text : undefined;
      add(name ?? "default", node);
      named.add(fn);
    } else if (ts.isFunctionExpression(node) && node.name !== undefined && !named.has(node)) {
      add(node.name.text, node);
    }
    ts.forEachChild(node, visit);
  };
  visit(file);
  return found;
}

function innermost(candidates: Context[]): string {
  let best: Context | undefined;
  for (const c of candidates) if (best === undefined || c.start >= best.start) best = c;
  return best?.name ?? "";
}

function collectComments(file: ts.SourceFile): Comment[] {
  const text = file.text;
  const ranges = new Map<number, ts.CommentRange>();
  const jsxText: [number, number][] = [];
  const addRanges = (found: ts.CommentRange[] | undefined): void => {
    for (const r of found ?? []) ranges.set(r.pos, r);
  };
  const visit = (node: ts.Node): void => {
    if (node.kind >= ts.SyntaxKind.FirstJSDocNode && node.kind <= ts.SyntaxKind.LastJSDocNode) return;
    if (node.kind === ts.SyntaxKind.JsxText || node.kind === ts.SyntaxKind.JsxTextAllWhiteSpaces) {
      jsxText.push([node.pos, node.end]);
      return;
    }
    const children = node.getChildren(file);
    if (children.length === 0) {
      addRanges(ts.getLeadingCommentRanges(text, node.pos));
      addRanges(ts.getTrailingCommentRanges(text, node.end));
      return;
    }
    for (const child of children) visit(child);
  };
  visit(file);
  const inJsxText = (pos: number): boolean => jsxText.some(([s, e]) => s <= pos && pos < e);
  const sorted = [...ranges.values()].filter((r) => !inJsxText(r.pos)).sort((a, b) => a.pos - b.pos);
  const comments: Comment[] = [];
  for (const r of sorted) {
    const lineStart = text.lastIndexOf("\n", r.pos - 1) + 1;
    const previous = comments.at(-1);
    const ownLine =
      /^[ \t]*$/.test(text.slice(lineStart, r.pos)) ||
      (previous !== undefined &&
        previous.ownLine &&
        previous.end >= lineStart &&
        /^[ \t]*$/.test(text.slice(previous.end, r.pos)));
    comments.push({
      pos: r.pos,
      end: r.end,
      multiLine: r.kind === ts.SyntaxKind.MultiLineCommentTrivia,
      ownLine,
    });
  }
  return comments;
}

function attachedComments(text: string, comments: Comment[], start: number): Set<number> {
  const run = new Set<number>();
  let cursor = start;
  for (let i = comments.length - 1; i >= 0; i--) {
    const c = comments[i];
    if (c === undefined || c.end > cursor) continue;
    if (!c.ownLine || !/^[ \t]*(?:\r?\n)?[ \t]*$/.test(text.slice(c.end, cursor))) break;
    run.add(c.pos);
    cursor = c.pos;
  }
  return run;
}

function eslintOffRules(config: string): string[] {
  const split = (s: string): string[] => {
    const parts: string[] = [];
    let depth = 0;
    let quote = "";
    let current = "";
    for (const ch of s) {
      if (quote !== "") {
        if (ch === quote) quote = "";
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if ("[{(".includes(ch)) {
        depth++;
      } else if ("]})".includes(ch)) {
        depth--;
      } else if (ch === "," && depth === 0) {
        parts.push(current);
        current = "";
        continue;
      }
      current += ch;
    }
    parts.push(current);
    return parts.map((p) => p.trim()).filter((p) => p !== "");
  };
  const unquote = (s: string): string => s.replace(/^(["'])([\s\S]*)\1$/, "$2");
  let body = config.trim();
  if (body.startsWith("{") && body.endsWith("}")) body = body.slice(1, -1);
  const off: string[] = [];
  for (const entry of split(body)) {
    const colon = entry.search(/:(?=(?:[^"']|["'][^"']*["'])*$)/);
    if (colon < 0) continue;
    let value = entry.slice(colon + 1).trim();
    if (value.startsWith("[")) value = split(value.slice(1, value.endsWith("]") ? -1 : undefined))[0] ?? "";
    const severity = unquote(value).toLowerCase();
    if (severity === "off" || value === "0") off.push(unquote(entry.slice(0, colon).trim()));
  }
  return off;
}

function commentForms(raw: string, multiLine: boolean, jsDoc: boolean): [tool: string, rule: string][] {
  const found: [string, string][] = [];
  const body = multiLine ? raw.slice(2, -2) : raw.slice(2);
  const trimmed = body.trim();
  const lines = body.split(/\r?\n|\r/);
  for (const line of lines) {
    const directive = TSC.exec(line)?.[1] ?? (TSC_NOCHECK.test(line) ? "ts-nocheck" : undefined);
    if (directive !== undefined) {
      found.push(["tsc", directive]);
      break;
    }
  }
  const disable = ESLINT_DISABLE.exec(trimmed.replace(ESLINT_DESCRIPTION, ""));
  if (disable !== null) {
    const rules = (disable[2] ?? "")
      .split(",")
      .map((r) => r.trim())
      .filter((r) => r !== "");
    for (const rule of rules.length > 0 ? rules : ["*"]) found.push(["eslint", rule]);
  }
  const config = multiLine ? ESLINT_CONFIG.exec(trimmed.replace(ESLINT_DESCRIPTION, "")) : null;
  if (config !== null) for (const rule of eslintOffRules(config[1] ?? "")) found.push(["eslint", rule]);
  if (trimmed === "prettier-ignore") found.push(["prettier", "ignore"]);
  const coverage = COVERAGE.exec(trimmed)?.[1];
  if (coverage !== undefined) found.push(["vitest-coverage", coverage]);
  if (jsDoc && PUBLIC.test(lines.map((l) => l.replace(/^[\s*]*/, "")).join("\n"))) {
    found.push(["knip", "public"]);
  }
  if (body.includes("jscpd:ignore-start")) found.push(["jscpd", "ignore"]);
  return found;
}

const FILE_WIDE = new Set(["tsc ts-nocheck", "vitest-coverage file"]);

function vitestNames(file: ts.SourceFile): { aliases: Map<string, string>; namespaces: Set<string> } {
  const aliases = new Map<string, string>();
  const namespaces = new Set<string>();
  for (const statement of file.statements) {
    if (
      !ts.isImportDeclaration(statement) ||
      !ts.isStringLiteral(statement.moduleSpecifier) ||
      statement.moduleSpecifier.text !== "vitest"
    ) {
      continue;
    }
    const bindings = statement.importClause?.namedBindings;
    if (bindings === undefined) continue;
    if (ts.isNamespaceImport(bindings)) {
      namespaces.add(bindings.name.text);
      continue;
    }
    for (const element of bindings.elements) {
      const imported = (element.propertyName ?? element.name).text;
      if (TEST_ROOTS.has(imported) || X_ROOTS.has(imported)) aliases.set(element.name.text, imported);
    }
  }
  return { aliases, namespaces };
}

function testMarkers(file: ts.SourceFile): { node: ts.Node; rule: string }[] {
  const { aliases, namespaces } = vitestNames(file);
  const found: { node: ts.Node; rule: string }[] = [];
  const counted = new Set<ts.Node>();
  // Returns the test API name a callee chain starts from, or undefined.
  const rootName = (expression: ts.Expression): { name: string; root: ts.Node } | undefined => {
    let n: ts.Expression = expression;
    let first: ts.PropertyAccessExpression | undefined;
    for (;;) {
      if (ts.isPropertyAccessExpression(n)) {
        first = n;
        n = n.expression;
      } else if (ts.isCallExpression(n) || ts.isTaggedTemplateExpression(n)) {
        first = undefined;
        n = ts.isCallExpression(n) ? n.expression : n.tag;
      } else {
        break;
      }
    }
    if (!ts.isIdentifier(n)) return undefined;
    const name = aliases.get(n.text) ?? n.text;
    if (TEST_ROOTS.has(name) || X_ROOTS.has(name)) return { name, root: n };
    if (namespaces.has(n.text) && first !== undefined) {
      const member = first.name.text;
      if (TEST_ROOTS.has(member) || X_ROOTS.has(member)) return { name: member, root: first };
    }
    return undefined;
  };
  const visit = (node: ts.Node): void => {
    if (ts.isPropertyAccessExpression(node) && MARKERS.has(node.name.text)) {
      const root = rootName(node.expression);
      if (root !== undefined && TEST_ROOTS.has(root.name)) found.push({ node, rule: node.name.text });
    }
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (
        ts.isPropertyAccessExpression(callee) &&
        callee.name.text === "skip" &&
        ts.isIdentifier(callee.expression) &&
        CONTEXT_NAMES.has(callee.expression.text)
      ) {
        found.push({ node, rule: "skip" });
      }
      const root = rootName(callee);
      if (root !== undefined && X_ROOTS.has(root.name) && !counted.has(root.root)) {
        counted.add(root.root);
        found.push({ node, rule: root.name });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(file);
  return found;
}

type Diagnostics = { parseDiagnostics?: readonly ts.Diagnostic[] };

function scanParsed(file: ts.SourceFile): Found[] {
  const text = file.text;
  const named = contexts(file);
  const comments = collectComments(file);
  const found: Found[] = [];
  const firstToken =
    file.statements[0]?.getStart(file) ?? file.endOfFileToken.getStart(file);
  const runs = new Map<number, Set<number>>();
  const attached = (start: number): Set<number> => {
    let run = runs.get(start);
    if (run === undefined) {
      run = attachedComments(text, comments, start);
      runs.set(start, run);
    }
    return run;
  };
  let header = false;
  for (const c of comments) {
    const raw = text.slice(c.pos, c.end);
    if (!header && c.end <= firstToken && GENERATED.some((r) => r.test(raw))) {
      header = true;
      found.push({ pos: c.pos, tool: "generated", rule: "generated", function: "" });
    }
    const forms = commentForms(raw, c.multiLine, raw.startsWith("/**") && raw !== "/**/");
    if (forms.length === 0) continue;
    const owners = named.filter(
      (n) =>
        (n.start <= c.pos && c.end <= n.end) ||
        (c.end <= n.attach && attached(n.attach).has(c.pos)),
    );
    const fn = innermost(owners);
    for (const [tool, rule] of forms) {
      found.push({ pos: c.pos, tool, rule, function: FILE_WIDE.has(`${tool} ${rule}`) ? "" : fn });
    }
  }
  for (const { node, rule } of testMarkers(file)) {
    const pos = node.getStart(file);
    const fn = innermost(named.filter((n) => n.start <= pos && node.end <= n.end));
    found.push({ pos, tool: "vitest", rule, function: fn });
  }
  return found.sort((a, b) => a.pos - b.pos);
}

export function scanText(text: string, fileName: string): Output[] {
  const extension = path.extname(fileName).toLowerCase();
  const kind = KINDS[extension] ?? ts.ScriptKind.TS;
  const file = ts.createSourceFile(
    fileName,
    text,
    { languageVersion: ts.ScriptTarget.Latest, jsDocParsingMode: ts.JSDocParsingMode.ParseNone },
    true,
    kind,
  );
  const first = (file as ts.SourceFile & Diagnostics).parseDiagnostics?.[0];
  if (first !== undefined) {
    const message = ts.flattenDiagnosticMessageText(first.messageText, "\n");
    const line = file.getLineAndCharacterOfPosition(first.start ?? 0).line + 1;
    return [{ file: fileName, error: `line ${line}: ${message}` }];
  }
  return scanParsed(file).map(({ tool, rule, function: fn }) => ({
    tool,
    file: fileName,
    rule,
    function: fn,
  }));
}

export function scanBytes(bytes: Uint8Array, fileName: string): Output[] {
  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return [{ file: fileName, error: "not valid UTF-8" }];
  }
  return scanText(text, fileName);
}

function main(root: string): void {
  const files = readFileSync(0, "utf8")
    .split("\0")
    .filter((f) => f !== "");
  const lines: string[] = [];
  for (const file of files) {
    let bytes: Uint8Array;
    try {
      bytes = readFileSync(path.join(root, file));
    } catch (error) {
      lines.push(JSON.stringify({ file, error: error instanceof Error ? error.message : String(error) }));
      continue;
    }
    for (const record of scanBytes(bytes, file)) lines.push(JSON.stringify(record));
  }
  if (lines.length > 0) process.stdout.write(`${lines.join("\n")}\n`);
}

const entry = process.argv[1];
if (entry !== undefined && realpathSync(entry) === fileURLToPath(import.meta.url)) {
  const root = process.argv[2];
  if (root === undefined) {
    console.error("usage: inline-exemptions.ts <root>");
    process.exitCode = 2;
  } else {
    main(root);
  }
}
