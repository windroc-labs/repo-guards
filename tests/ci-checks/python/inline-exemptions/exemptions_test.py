class Protocol(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.root = Path(self.dir.name)

    def write(self, path, content):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, str):
            content = content.encode()
        file.write_bytes(content)

    def records(self, paths):
        done = run_scanner(self.root, paths)
        self.assertEqual(done.returncode, 0, done.stderr)
        return [json.loads(line) for line in done.stdout.decode().splitlines()]

    def test_paths_on_stdin_give_json_lines(self):
        self.write("src/m.py", "def f():\n    x = 1  # noqa: E501\n")
        self.write("stubs/x.pyi", "x: int  # type: ignore\n")
        self.write("pyproject.toml", '[tool.deptry]\nignore = ["DEP003"]\n')
        self.write("src/clean.py", "x = 1\n")
        records = self.records(["src/m.py", "stubs/x.pyi", "pyproject.toml", "src/clean.py"])
        self.assertCountEqual(
            records,
            [
                {"tool": "ruff", "file": "src/m.py", "rule": "E501", "function": "f"},
                {"tool": "pyright", "file": "stubs/x.pyi", "rule": "*", "function": ""},
                {"tool": "deptry", "file": "pyproject.toml", "rule": "DEP003", "function": ""},
            ],
        )
        self.assertEqual(list(records[0]), ["tool", "file", "rule", "function"])

    def test_s23_unreadable_files_are_error_records_and_scanning_continues(self):
        self.write("src/x.py", "def f(:\n")
        self.write("src/y.py", b"x = '\xff'\n")
        self.write("src/z.py", "x = 1  # noqa\n")
        self.write("pyproject.toml", "[tool.deptry\n")
        records = self.records(["src/x.py", "src/y.py", "src/z.py", "pyproject.toml"])
        errors = {r["file"] for r in records if "error" in r}
        self.assertEqual(errors, {"src/x.py", "src/y.py", "pyproject.toml"})
        for record in records:
            if "error" in record:
                self.assertEqual(set(record), {"file", "error"})
                self.assertTrue(record["error"])
        self.assertIn({"tool": "ruff", "file": "src/z.py", "rule": "*", "function": ""}, records)

    def test_s34_scanned_code_is_never_executed(self):
        marker = self.root / "pwned"
        code = f"open({str(marker)!r}, 'w').close()\nimport pytest  # noqa\n"
        self.write("tests/conftest.py", code)
        self.write("setup.py", code)
        self.write("pyproject.toml", '[build-system]\nrequires = ["setuptools"]\n')
        records = self.records(["tests/conftest.py", "setup.py", "pyproject.toml"])
        self.assertEqual(len(records), 2)
        self.assertFalse(marker.exists())

    def test_no_input_gives_no_output(self):
        self.assertEqual(self.records([]), [])


