import textwrap
import unittest

from go_source import extract
from syntax import SourceError


def hits(source: str, path: str = "pkg/a.go") -> list[tuple[str, str, str]]:
    return extract(path, textwrap.dedent(source).encode())


def in_method(line: str) -> str:
    return f"package a\n\nfunc (t T) Run() {{\n\t{line}\n}}\n"


class FormsTest(unittest.TestCase):
    def test_s40_forms_in_method(self) -> None:
        rows = [
            ("x := f() //nolint:errcheck // 说明", "golangci-lint", "errcheck"),
            ("y := g() //nolint", "golangci-lint", "*"),
            ('t.Skip("flaky")', "go-test", "Skip"),
            ("t.SkipNow()", "go-test", "SkipNow"),
        ]
        for line, tool, rule in rows:
            with self.subTest(line):
                self.assertEqual(hits(in_method(line)), [(tool, rule, "T.Run")])

    def test_s41_pointer_receiver_and_file_nolint(self) -> None:
        source = """\
            //nolint:all
            package b

            func (s *Srv[K]) Stop() {
            \t//nolint:gosec
            \tx := run()
            }
            """
        self.assertEqual(hits(source, "pkg/b.go"), [("golangci-lint", "*", ""), ("golangci-lint", "gosec", "Srv.Stop")])

    def test_s42_build_constraints(self) -> None:
        self.assertEqual(hits("//go:build linux\n\npackage c\n", "pkg/c_linux.go"), [("go-build", "linux", "")])
        self.assertEqual(hits("//go:build integration\n\npackage c\n", "pkg/it_test.go"), [("go-build", "integration", "")])

    def test_old_build_lines(self) -> None:
        source = "//go:build linux && !arm64\n// +build linux,!arm64\n\npackage c\n"
        self.assertEqual(hits(source), [("go-build", "linux && !arm64", ""), ("go-build", "linux,!arm64", "")])

    def test_s10_jscpd(self) -> None:
        source = "package a\n\nfunc f() {\n\t// jscpd:ignore-start\n\tx := 1\n\t// jscpd:ignore-end\n}\n"
        self.assertEqual(hits(source), [("jscpd", "ignore", "f")])

    def test_s14_nosec_not_builtin(self) -> None:
        self.assertEqual(hits(in_method("x := f() // #nosec G115")), [])

    def test_s29_strings_are_not_comments(self) -> None:
        self.assertEqual(hits(in_method('y := "//nolint"\n\tz := `//nolint:errcheck`')), [])

    def test_s44_generated_header(self) -> None:
        source = "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: x.proto\n\npackage api\n"
        self.assertEqual(hits(source, "api/x.pb.go"), [("generated", "generated", "")])
        self.assertEqual(hits("package api\n\n// Code generated by x. DO NOT EDIT.\n"), [])


class NolintTest(unittest.TestCase):
    def test_linter_list(self) -> None:
        self.assertEqual(hits(in_method("x := f() //nolint:a,b")), [("golangci-lint", "a", "T.Run"), ("golangci-lint", "b", "T.Run")])
        self.assertEqual(hits(in_method("x := f() //nolint:all")), [("golangci-lint", "*", "T.Run")])
        self.assertEqual(hits(in_method("x := f() //NoLint:errcheck")), [("golangci-lint", "errcheck", "T.Run")])

    def test_space_after_slashes_is_not_nolint(self) -> None:
        self.assertEqual(hits(in_method("x := f() // nolint")), [])
        self.assertEqual(hits(in_method("x := f() //nolintx")), [])

    def test_nolint_above_function(self) -> None:
        source = """\
            package a

            //nolint:gocyclo
            // F does a lot.
            func F() {}

            //nolint:unused
            var v = 1
            """
        self.assertEqual(hits(source), [("golangci-lint", "gocyclo", "F"), ("golangci-lint", "unused", "")])


class FunctionsTest(unittest.TestCase):
    def test_func_literal_belongs_to_enclosing_function(self) -> None:
        source = """\
            package a

            func F(t *testing.T) {
            \tgo func() {
            \t\tt.Skipf("x %d", 1)
            \t}()
            }
            """
        self.assertEqual(hits(source), [("go-test", "Skipf", "F")])

    def test_receiver_types(self) -> None:
        source = """\
            package a

            func (*T) M() { t.Skip() }
            func (v Map[K, V]) N() { t.Skip() }
            func G[K any]() { t.Skip() }
            """
        self.assertEqual(hits(source), [("go-test", "Skip", "T.M"), ("go-test", "Skip", "Map.N"), ("go-test", "Skip", "G")])

    def test_outside_functions(self) -> None:
        self.assertEqual(hits("package a\n\nvar x = f() //nolint:errcheck\n"), [("golangci-lint", "errcheck", "")])


class ErrorTest(unittest.TestCase):
    def test_s23_syntax_error(self) -> None:
        with self.assertRaises(SourceError) as raised:
            hits("package v\n\nfunc f( {\n}\n", "pkg/v.go")
        self.assertIn("syntax error", str(raised.exception))


if __name__ == "__main__":
    unittest.main()
