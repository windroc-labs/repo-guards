import ast
import io
import json
import os
import re
import sys
import tokenize
import tomllib
from pathlib import Path, PurePosixPath

USAGE = "usage: exemptions.py <repo root>  (NUL-separated relative paths on stdin)"

CODE = r"[A-Za-z]+[0-9]+"
CODES = rf"(?:\s*:\s*(?P<codes>{CODE}(?:[\s,]+{CODE})*))?"
END = r"(?![\w-])"
RULES = rf"(?:\[(?P<rules>[^\]]*)\]|{END})"
SETTING = r"[A-Za-z]\w*(?:\s*=\s*\w+)?"


def pattern(text, flags=re.IGNORECASE):
    return re.compile(text, flags)


FILE_NOQA = pattern(rf"#\s*(?:ruff|flake8)\s*:\s*noqa{END}{CODES}")
NOQA = pattern(rf"#\s*noqa{END}{CODES}")
FMT = pattern(rf"#\s*fmt\s*:\s*(?P<word>off|skip){END}")
YAPF = pattern(rf"#\s*yapf\s*:\s*disable{END}")
TYPE_IGNORE = pattern(rf"#\s*type\s*:\s*ignore{RULES}")
PYRIGHT_IGNORE = pattern(rf"#\s*pyright\s*:\s*ignore{RULES}")
PYRIGHT_SETTINGS = pattern(rf"#\s*pyright\s*:\s*(?P<settings>{SETTING}(?:\s*,\s*{SETTING})*)")
NO_COVER = pattern(r"#\s*(pragma|PRAGMA)[:\s]?\s*(no|NO)\s*(cover|COVER)", 0)
NO_BRANCH = pattern(r"#\s*(pragma|PRAGMA)[:\s]?\s*(no|NO)\s*(branch|BRANCH)", 0)

GENERATED = re.compile(
    r"@generated|Code generated .* DO NOT EDIT\.|"
    r"Generated by the protocol buffer compiler\.  DO NOT EDIT!"
)

MARKERS = {
    "pytest.mark.skip": "pytest",
    "pytest.mark.skipif": "pytest",
    "pytest.mark.xfail": "pytest",
    "pytest.skip": "pytest",
    "pytest.xfail": "pytest",
    "pytest.importorskip": "pytest",
    "unittest.skip": "unittest",
    "unittest.skipIf": "unittest",
    "unittest.skipUnless": "unittest",
    "unittest.expectedFailure": "unittest",
    "unittest.SkipTest": "unittest",
}

NOT_CODE = {
    tokenize.COMMENT,
    tokenize.NL,
    tokenize.NEWLINE,
    tokenize.ENCODING,
    tokenize.INDENT,
    tokenize.DEDENT,
    tokenize.ENDMARKER,
}


class Error(Exception):
    pass


def noqa_rules(codes):
    if not codes:
        return [("ruff", "*")]
    return [
        ("vulture" if code[0] in "Vv" else "ruff", code) for code in re.split(r"[\s,]+", codes)
    ]


def bracket_rules(rules):
    names = [r.strip() for r in (rules or "").split(",") if r.strip()]
    return [("pyright", name) for name in names] or [("pyright", "*")]


def directive(comment, at):
    """Returns ([(tool, rule)], file_level) for the directive starting at `comment[at]`."""
    if m := FILE_NOQA.match(comment, at):
        return noqa_rules(m["codes"]), True
    if m := NOQA.match(comment, at):
        return noqa_rules(m["codes"]), False
    if m := FMT.match(comment, at):
        return [("ruff-format", m["word"].lower())], False
    if YAPF.match(comment, at):
        return [("ruff-format", "off")], False
    if m := TYPE_IGNORE.match(comment, at) or PYRIGHT_IGNORE.match(comment, at):
        return bracket_rules(m["rules"]), False
    if m := PYRIGHT_SETTINGS.match(comment, at):
        names = [s.split("=")[0].strip() for s in m["settings"].split(",")]
        return [("pyright", name) for name in names], True
    if NO_COVER.match(comment, at):
        return [("coverage", "no cover")], False
    if NO_BRANCH.match(comment, at):
        return [("coverage", "no branch")], False
    return [], False


def comment_occurrences(comment, function):
    found = []
    for hash_mark in re.finditer("#", comment):
        rules, file_level = directive(comment, hash_mark.start())
        found += [(tool, rule, "" if file_level else function) for tool, rule in rules]
    if "jscpd:ignore-start" in comment:
        found.append(("jscpd", "ignore", function))
    return found


def import_aliases(tree):
    aliases = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    aliases[alias.asname] = alias.name
                else:
                    top = alias.name.split(".")[0]
                    aliases[top] = top
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            for alias in node.names:
                if alias.name != "*":
                    aliases[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return aliases


def dotted(node):
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        base = dotted(node.value)
        return base and f"{base}.{node.attr}"
    return None


class Walker:
    def __init__(self, aliases):
        self.aliases = aliases
        self.functions = []
        self.found = []

    def resolve(self, node):
        name = dotted(node)
        if name is None:
            return None
        head, dot, rest = name.partition(".")
        return self.aliases.get(head, head) + dot + rest

    def check(self, node, function):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "skipTest"
        ):
            self.found.append(("unittest", "skipTest", function))
        elif isinstance(node, (ast.Name, ast.Attribute)) and isinstance(node.ctx, ast.Load):
            name = self.resolve(node)
            if name in MARKERS:
                self.found.append((MARKERS[name], name.rpartition(".")[2], function))

    def visit(self, node, function="", owner="", depth=0):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            name = f"{owner}.{node.name}" if owner else node.name
            start = min([node.lineno] + [d.lineno for d in node.decorator_list])
            self.functions.append((start, node.end_lineno, depth + 1, name))
            for child in ast.iter_child_nodes(node):
                self.visit(child, name, "", depth + 1)
            return
        if isinstance(node, ast.ClassDef):
            body = {id(stmt) for stmt in node.body}
            for child in ast.iter_child_nodes(node):
                inside = id(child) in body
                self.visit(child, function, node.name if inside else owner, depth)
            return
        self.check(node, function)
        for child in ast.iter_child_nodes(node):
            self.visit(child, function, owner, depth)


def function_at(functions, line):
    """Innermost function whose range, extended by the comment run above it, holds `line`."""
    best = None
    for start, end, depth, name in functions:
        if start <= line <= end and (best is None or depth > best[0]):
            best = (depth, name)
    return best[1] if best else ""


def attach_comment_runs(functions, comment_only):
    extended = []
    for start, end, depth, name in functions:
        while start - 1 in comment_only:
            start -= 1
        extended.append((start, end, depth, name))
    return extended


def whitelist_names(tree):
    return [
        name
        for stmt in tree.body
        if isinstance(stmt, ast.Expr) and (name := dotted(stmt.value)) is not None
    ]


def scan_python(path, text):
    try:
        tree = ast.parse(text, filename=path)
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (SyntaxError, ValueError, tokenize.TokenError, RecursionError, MemoryError) as error:
        raise Error(describe(error)) from error
    walker = Walker(import_aliases(tree))
    try:
        walker.visit(tree)
    except RecursionError as error:
        raise Error("too deeply nested to scan") from error
    comments = [t for t in tokens if t.type == tokenize.COMMENT]
    comment_only = {t.start[0] for t in comments if not t.line[: t.start[1]].strip()}
    functions = attach_comment_runs(walker.functions, comment_only)

    found = []
    for token in tokens:
        if token.type not in NOT_CODE:
            break
        if token.type == tokenize.COMMENT and GENERATED.search(token.string):
            found.append(("generated", "generated", ""))
            break
    for comment in comments:
        found += comment_occurrences(comment.string, function_at(functions, comment.start[0]))
    found += walker.found
    if "whitelist" in PurePosixPath(path).name.lower():
        found += [("vulture", name, "") for name in whitelist_names(tree)]
    return found


def scan_pyproject(text):
    try:
        config = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise Error(f"invalid TOML: {error}") from error
    deptry = config.get("tool", {}).get("deptry", {})
    if not isinstance(deptry, dict):
        return []
    found = []
    ignore = deptry.get("ignore", [])
    if isinstance(ignore, list):
        found += [("deptry", code, "") for code in ignore if isinstance(code, str)]
    per_rule = deptry.get("per_rule_ignores", {})
    if isinstance(per_rule, dict):
        for code, packages in per_rule.items():
            if isinstance(packages, list):
                found += [
                    ("deptry", f"{code}:{package}", "")
                    for package in packages
                    if isinstance(package, str)
                ]
    return found


def scan_text(path, text):
    """Returns the (tool, file, rule, function) occurrences in one file's text."""
    if PurePosixPath(path).name == "pyproject.toml":
        found = scan_pyproject(text)
    else:
        found = scan_python(path, text)
    return [(tool, path, rule, function) for tool, rule, function in found]


def describe(error):
    if isinstance(error, SyntaxError):
        return f"syntax error: {error.msg} (line {error.lineno})"
    if isinstance(error, tokenize.TokenError):
        return f"tokenize error: {error.args[0]}"
    if isinstance(error, RecursionError):
        return "too deeply nested to parse"
    return f"cannot parse: {error}"


def scan_file(root, path):
    try:
        text = (root / path).read_bytes().decode("utf-8").removeprefix("﻿")
        occurrences = scan_text(path, text)
    except OSError as error:
        return [{"file": path, "error": f"cannot read: {error.strerror}"}]
    except UnicodeDecodeError as error:
        return [{"file": path, "error": f"not UTF-8 (byte {error.start})"}]
    except Error as error:
        return [{"file": path, "error": str(error)}]
    return [
        {"tool": tool, "file": file, "rule": rule, "function": function}
        for tool, file, rule, function in occurrences
    ]


def main(argv, stdin, stdout):
    if len(argv) != 2:
        print(USAGE, file=sys.stderr)
        return 2
    root = Path(argv[1])
    for raw in stdin.read().split(b"\0"):
        if raw:
            for record in scan_file(root, os.fsdecode(raw)):
                stdout.write(json.dumps(record) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv, sys.stdin.buffer, sys.stdout))
